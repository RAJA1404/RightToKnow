function decodeIfNeeded(value) {
  if (typeof value !== 'string') return value;

  try {
    if (/[ÃÂâà]/.test(value)) {
      return decodeURIComponent(escape(value));
    }
  } catch (_error) {
    return value;
  }

  return value;
}

export function translate(lang, key) {
  const entry = portalText[key];
  if (!entry) {
    return key;
  }

  return decodeIfNeeded(entry[lang] || entry.en || key);
}

